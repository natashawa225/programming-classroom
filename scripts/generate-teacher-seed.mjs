// Generates a SQL file that creates (or updates) a teacher account.
//
// Usage:
//   node scripts/generate-teacher-seed.mjs --username jdoe --name "Jane Doe" [--password "..."] [--assign-orphan-sessions]
//
// If --password is omitted, a random one is generated and printed once (it is
// not saved anywhere). Pass --assign-orphan-sessions to also attach any
// existing sessions that don't yet belong to a teacher (teacher_id IS NULL)
// to this account — use this once, for the first teacher, when migrating off
// the old shared-password login.
//
// This only writes a .sql file; nothing is applied to your database until you
// run the generated file yourself (e.g. in the Supabase SQL editor), matching
// the rest of this repo's scripts/*.sql migrations.

import { randomBytes } from 'node:crypto'
import { mkdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import bcrypt from 'bcryptjs'

function parseArgs(argv) {
  const args = { assignOrphanSessions: false }
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i]
    if (arg === '--username') args.username = argv[++i]
    else if (arg === '--name') args.name = argv[++i]
    else if (arg === '--password') args.password = argv[++i]
    else if (arg === '--assign-orphan-sessions') args.assignOrphanSessions = true
    else {
      console.error(`Unknown argument: ${arg}`)
      process.exit(1)
    }
  }
  return args
}

function generatePassword() {
  return randomBytes(12).toString('base64url')
}

function sqlEscape(value) {
  return value.replace(/'/g, "''")
}

const args = parseArgs(process.argv.slice(2))

const username = (args.username || '').trim().toLowerCase()
if (!username) {
  console.error('Missing --username "jdoe"')
  process.exit(1)
}

const name = args.name ? args.name.trim() : null
const generatedPassword = args.password ? null : generatePassword()
const password = args.password || generatedPassword

const passwordHash = bcrypt.hashSync(password, 10)

const usernameLiteral = `'${sqlEscape(username)}'`
const nameLiteral = name ? `'${sqlEscape(name)}'` : 'NULL'
const passwordHashLiteral = `'${sqlEscape(passwordHash)}'`

const statements = [
  '-- Generated by scripts/generate-teacher-seed.mjs',
  '-- Review before running. Safe to re-run: updates the password/name if the username already exists.',
  'BEGIN;',
  '',
  'WITH upserted_teacher AS (',
  '  INSERT INTO teachers (username, name, password_hash)',
  `  VALUES (${usernameLiteral}, ${nameLiteral}, ${passwordHashLiteral})`,
  '  ON CONFLICT (username) DO UPDATE',
  '  SET name = EXCLUDED.name, password_hash = EXCLUDED.password_hash',
  '  RETURNING id',
  ')',
]

if (args.assignOrphanSessions) {
  statements.push(
    'UPDATE sessions',
    'SET teacher_id = (SELECT id FROM upserted_teacher)',
    'WHERE teacher_id IS NULL;'
  )
} else {
  // No-op select so the CTE still executes even when there's nothing else to do.
  statements.push('SELECT id FROM upserted_teacher;')
}

statements.push('', 'COMMIT;', '')

const sql = statements.join('\n')

const outputDir = join(process.cwd(), 'scripts', 'generated')
mkdirSync(outputDir, { recursive: true })
const safeUsername = username.replace(/[^a-z0-9]+/g, '_')
const outputPath = join(outputDir, `teacher_seed_${safeUsername}.sql`)
writeFileSync(outputPath, sql)

console.log(`Generated: ${outputPath}`)
console.log('Run this file against your database (e.g. Supabase SQL editor) to apply it.')
if (generatedPassword) {
  console.log('')
  console.log(`Generated password for ${username}: ${generatedPassword}`)
  console.log('Save this now — it is not stored anywhere and cannot be recovered.')
}
if (args.assignOrphanSessions) {
  console.log('')
  console.log('This will also attach any sessions with no teacher_id to this account.')
}
